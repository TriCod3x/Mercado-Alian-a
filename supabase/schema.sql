-- =====================================================================
-- Mercado Aliança — estrutura do banco (Supabase / PostgreSQL 15+)
--
-- Como usar: Supabase → SQL Editor → New query → cole este arquivo
-- inteiro → Run. Rode UMA vez num projeto novo (o script para com erro
-- se as tabelas já existirem, para não mexer em dados).
--
-- Convenções herdadas do sistema original (SQLite):
--   * Dinheiro sempre em CENTAVOS inteiros (bigint).
--   * Quantidades em MILÉSIMOS inteiros (1 un = 1000; 0,5 kg = 500).
--   * IDs numéricos preservados (identity "by default" permite que a
--     migração grave os IDs antigos).
--
-- Segurança: o navegador NUNCA fala com o Supabase. Só o backend Node
-- acessa o banco, pela connection string do Postgres. Por isso:
--   * RLS ligado em todas as tabelas e SEM nenhuma policy → a API
--     pública do Supabase (anon / authenticated) não lê nem grava nada.
--   * Permissões das roles anon/authenticated revogadas.
--   * As regras de dono/caixa continuam sendo aplicadas no servidor.
-- =====================================================================

BEGIN;

-- ---------- usuários e sessões ----------------------------------------

CREATE TABLE users (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text        NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  username    text        NOT NULL CHECK (username = lower(username) AND length(username) BETWEEN 1 AND 64),
  pass_hash   text        NOT NULL CHECK (pass_hash LIKE 'scrypt$%$%'),
  role        text        NOT NULL CHECK (role IN ('dono', 'caixa')),
  active      boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_username ON users (username);

-- Guarda só o SHA-256 do token; o token em si fica apenas no cookie httpOnly.
CREATE TABLE sessions (
  token_hash  text        PRIMARY KEY CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  user_id     bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  touched_at  timestamptz NOT NULL
);
CREATE INDEX ix_sessions_user ON sessions (user_id);
CREATE INDEX ix_sessions_expires ON sessions (expires_at);

-- ---------- catálogo ----------------------------------------------------

CREATE TABLE categories (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text        NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 60),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
-- Equivale ao "UNIQUE COLLATE NOCASE" do SQLite.
CREATE UNIQUE INDEX ux_categories_name ON categories (lower(name));

CREATE TABLE products (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  category_id  bigint      NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
  code         text        CHECK (code IS NULL OR length(code) BETWEEN 1 AND 64),
  unit         text        NOT NULL CHECK (unit IN ('un', 'kg')),
  cost_cents   bigint      NOT NULL CHECK (cost_cents >= 0),   -- último preço de compra
  price_cents  bigint      NOT NULL CHECK (price_cents > 0),
  stock_milli  bigint      NOT NULL CHECK (stock_milli >= 0),  -- estoque nunca negativo
  min_milli    bigint      NOT NULL DEFAULT 0 CHECK (min_milli >= 0),
  active       boolean     NOT NULL DEFAULT true,              -- exclusão lógica
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  -- produto "un" só aceita quantidades inteiras
  CHECK (unit = 'kg' OR (stock_milli % 1000 = 0 AND min_milli % 1000 = 0))
);
-- Código de barras único apenas entre produtos ativos (excluído libera o código).
CREATE UNIQUE INDEX ux_products_code ON products (code) WHERE code IS NOT NULL AND active;
CREATE INDEX ix_products_category ON products (category_id);
CREATE INDEX ix_products_active_name ON products (lower(name)) WHERE active;

-- ---------- vendas ------------------------------------------------------

CREATE TABLE sales (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number          integer     NOT NULL CHECK (number > 0),     -- nº sequencial sem buracos
  request_id      text        CHECK (request_id IS NULL OR length(request_id) BETWEEN 1 AND 80),
  user_id         bigint      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  created_at      timestamptz NOT NULL DEFAULT now(),
  subtotal_cents  bigint      NOT NULL CHECK (subtotal_cents > 0),
  discount_cents  bigint      NOT NULL DEFAULT 0 CHECK (discount_cents >= 0),
  total_cents     bigint      NOT NULL CHECK (total_cents > 0),
  cost_cents      bigint      NOT NULL CHECK (cost_cents >= 0),
  payment         text        NOT NULL CHECK (payment IN ('dinheiro', 'pix', 'debito', 'credito')),
  received_cents  bigint,
  status          text        NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'cancelada')),
  cancelled_at    timestamptz,
  cancelled_by    bigint      REFERENCES users (id) ON DELETE RESTRICT,
  cancel_reason   text        CHECK (cancel_reason IS NULL OR length(cancel_reason) <= 200),
  CONSTRAINT ux_sales_number UNIQUE (number),
  CONSTRAINT ux_sales_request UNIQUE (request_id),             -- anti-duplicidade
  CHECK (discount_cents <= subtotal_cents),
  CHECK (total_cents = subtotal_cents - discount_cents),
  CHECK (received_cents IS NULL OR (payment = 'dinheiro' AND received_cents >= total_cents)),
  CHECK ((status = 'ok' AND cancelled_at IS NULL AND cancelled_by IS NULL)
      OR (status = 'cancelada' AND cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL))
);
CREATE INDEX ix_sales_created ON sales (created_at);
CREATE INDEX ix_sales_user_created ON sales (user_id, created_at);
CREATE INDEX ix_sales_cancelled_by ON sales (cancelled_by) WHERE cancelled_by IS NOT NULL;

-- Itens guardam nome, categoria, preço e custo DA ÉPOCA da venda.
CREATE TABLE sale_items (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id           bigint NOT NULL REFERENCES sales (id) ON DELETE RESTRICT,
  product_id        bigint NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  name              text   NOT NULL,
  category          text   NOT NULL,
  unit              text   NOT NULL CHECK (unit IN ('un', 'kg')),
  qty_milli         bigint NOT NULL CHECK (qty_milli > 0),
  price_cents       bigint NOT NULL CHECK (price_cents >= 0),
  cost_cents        bigint NOT NULL CHECK (cost_cents >= 0),
  total_cents       bigint NOT NULL CHECK (total_cents >= 0),   -- antes do desconto
  discount_cents    bigint NOT NULL DEFAULT 0 CHECK (discount_cents >= 0),
  cost_total_cents  bigint NOT NULL CHECK (cost_total_cents >= 0),
  CHECK (discount_cents <= total_cents)
);
CREATE INDEX ix_items_sale ON sale_items (sale_id);
CREATE INDEX ix_items_product ON sale_items (product_id);

-- ---------- histórico de estoque ---------------------------------------

CREATE TABLE stock_movements (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  bigint      NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  type        text        NOT NULL CHECK (type IN ('inicial', 'entrada', 'ajuste', 'venda', 'cancelamento')),
  qty_milli   bigint      NOT NULL CHECK (qty_milli <> 0),      -- positivo entra, negativo sai
  note        text,
  user_id     bigint      REFERENCES users (id) ON DELETE RESTRICT,
  sale_id     bigint      REFERENCES sales (id) ON DELETE RESTRICT,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CHECK (type IN ('venda', 'cancelamento') = (sale_id IS NOT NULL)),
  CHECK (type = 'ajuste' OR (type = 'venda') = (qty_milli < 0))
);
CREATE INDEX ix_mov_product ON stock_movements (product_id, created_at DESC, id DESC);
CREATE INDEX ix_mov_sale ON stock_movements (sale_id) WHERE sale_id IS NOT NULL;

-- ---------- auditoria: updated_at automático ----------------------------

CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

CREATE TRIGGER trg_users_updated BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_categories_updated BEFORE UPDATE ON categories
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_products_updated BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------- proteção: RLS + nenhuma permissão para a API pública --------

ALTER TABLE users           ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions        ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories      ENABLE ROW LEVEL SECURITY;
ALTER TABLE products        ENABLE ROW LEVEL SECURITY;
ALTER TABLE sales           ENABLE ROW LEVEL SECURITY;
ALTER TABLE sale_items      ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_movements ENABLE ROW LEVEL SECURITY;
-- Propositalmente NÃO há "CREATE POLICY": sem policy, RLS nega tudo para
-- anon/authenticated. O backend conecta como dono das tabelas (postgres),
-- que não passa pelo RLS, e faz a autorização de dono/caixa no código.

DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON users, sessions, categories, products, sales, sale_items, stock_movements FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA %I FROM %I', current_schema(), r);
      EXECUTE format('REVOKE EXECUTE ON FUNCTION set_updated_at() FROM %I', r);
    END IF;
  END LOOP;
END $$;
REVOKE EXECUTE ON FUNCTION set_updated_at() FROM PUBLIC;

COMMIT;
